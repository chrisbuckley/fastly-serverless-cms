#!/usr/bin/env bash
# Extract inline VCL snippets from a Terraform file and wrap each one in a
# standalone, lintable VCL file for `falco lint`.
#
# Usage: scripts/extract-vcl.sh [terraform/vcl.tf] [output-dir]
#
# For every `snippet { name = "x" type = "recv" content = <<-VCL ... VCL }`
# block this writes:
#   <out>/snippets/<name>.<type>.vcl   raw snippet body (Terraform escapes resolved)
#   <out>/lint/<name>.vcl              snippet wrapped in its subroutine, plus
#                                      stub backends/tables derived from the same .tf
#
# Each snippet is wrapped on its own (not merged) so `declare local` ordering
# and unrelated snippets cannot interfere. Then:  falco lint <out>/lint/*.vcl
#
# Terraform templating is neutralised: `$${` -> `${`, `${...}` -> `placeholder`,
# `%%{` -> `%{`.
set -euo pipefail

TF_FILE="${1:-terraform/vcl.tf}"
OUT_DIR="${2:-}"

if [ ! -f "$TF_FILE" ]; then
    echo "extract-vcl: $TF_FILE not found" >&2
    exit 2
fi
if [ -z "$OUT_DIR" ]; then
    OUT_DIR=$(mktemp -d)
fi
SNIP_DIR="$OUT_DIR/snippets"
LINT_DIR="$OUT_DIR/lint"
rm -rf "$SNIP_DIR" "$LINT_DIR"
mkdir -p "$SNIP_DIR" "$LINT_DIR"

# --- 1. Pull snippet blocks out of the Terraform file ----------------------
# Emits: <name>\t<type>\t<file> via files written into $SNIP_DIR.
awk -v dir="$SNIP_DIR" '
function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
function strval(line,   v) {
    v = line
    sub(/^[^"]*"/, "", v)
    sub(/".*$/, "", v)
    return v
}
{
    line = $0
    if (in_heredoc) {
        if (trim(line) == marker) {
            in_heredoc = 0
            close(outfile)
            next
        }
        print line >> outfile
        next
    }
    if (line ~ /^[ \t]*snippet[ \t]*\{/) { in_snip = 1; name = ""; type = ""; next }
    if (!in_snip) next
    if (line ~ /^[ \t]*name[ \t]*=/ && name == "") { name = strval(line); next }
    if (line ~ /^[ \t]*type[ \t]*=/ && type == "") { type = strval(line); next }
    if (line ~ /^[ \t]*content[ \t]*=[ \t]*<<-?[A-Za-z_]+[ \t]*$/) {
        marker = line
        sub(/^.*<<-?/, "", marker)
        marker = trim(marker)
        if (name == "" || type == "") {
            print "extract-vcl: snippet content before name/type (name=" name ", type=" type ")" > "/dev/stderr"
            exit 3
        }
        outfile = dir "/" name "." type ".vcl"
        printf "" > outfile
        in_heredoc = 1
        in_snip = 0
        count++
        next
    }
}
END {
    if (in_heredoc) { print "extract-vcl: unterminated heredoc" > "/dev/stderr"; exit 4 }
}
' "$TF_FILE"

# --- 2. Neutralise Terraform templating in the extracted bodies ------------
for f in "$SNIP_DIR"/*.vcl; do
    [ -e "$f" ] || continue
    # perl (not sed) so behaviour is identical on macOS and Linux runners.
    perl -pe 's/\$\$\{/\x01{/g; s/\$\{[^}]*\}/placeholder/g; s/\x01\{/\${/g; s/%%\{/%{/g' "$f" >"$f.tmp"
    mv "$f.tmp" "$f"
done

# --- 3. Derive stub backends and tables from the same Terraform file -------
# Fastly exposes backend "edge-cms-compute" as F_edge_cms_compute.
block_names() {
    # $1 = block keyword (backend|dictionary)
    awk -v kw="$1" '
    $0 ~ "^[ \t]*" kw "[ \t]*\\{" { want = 1; next }
    want && /^[ \t]*name[ \t]*=/ {
        v = $0; sub(/^[^"]*"/, "", v); sub(/".*$/, "", v)
        print v
        want = 0
    }' "$TF_FILE"
}

PRELUDE="$OUT_DIR/prelude.vcl"
{
    echo "# Generated by scripts/extract-vcl.sh — stubs so snippets resolve standalone."
    block_names backend | while read -r b; do
        id=$(printf '%s' "$b" | tr -c 'A-Za-z0-9\n' '_')
        printf 'backend F_%s {\n  .host = "127.0.0.1";\n  .port = "80";\n}\n\n' "$id"
    done
    block_names dictionary | while read -r d; do
        id=$(printf '%s' "$d" | tr -c 'A-Za-z0-9\n' '_')
        printf 'table %s STRING {\n  "stub": "stub",\n}\n\n' "$id"
    done
} >"$PRELUDE"

# Subroutine snippets may use objects (ratecounters, penaltyboxes, tables)
# declared by `init` snippets, so include those declarations ahead of them.
INIT_DECLS="$OUT_DIR/init-decls.vcl"
: >"$INIT_DECLS"
for f in "$SNIP_DIR"/*.init.vcl; do
    [ -e "$f" ] || continue
    cat "$f" >>"$INIT_DECLS"
done

# --- 4. Wrap each snippet in its subroutine --------------------------------
shopt -s nullglob
n=0
for f in "$SNIP_DIR"/*.vcl; do
    base=$(basename "$f" .vcl)
    type="${base##*.}"
    name="${base%.*}"
    out="$LINT_DIR/$name.vcl"
    case "$type" in
    init | none)
        cat "$PRELUDE" "$f" >"$out"
        ;;
    recv | hash | hit | miss | pass | fetch | error | deliver | log)
        {
            cat "$PRELUDE" "$INIT_DECLS"
            printf 'sub vcl_%s {\n  #FASTLY %s\n\n' "$type" "$type"
            cat "$f"
            case "$type" in
            recv) printf '\n  return(lookup);\n' ;;
            hash) printf '\n  return(hash);\n' ;;
            hit) printf '\n  return(deliver);\n' ;;
            miss) printf '\n  return(fetch);\n' ;;
            pass) printf '\n  return(pass);\n' ;;
            fetch) printf '\n  return(deliver);\n' ;;
            error) printf '\n  return(deliver);\n' ;;
            deliver) printf '\n  return(deliver);\n' ;;
            log) printf '\n  return(deliver);\n' ;;
            esac
            printf '}\n'
        } >"$out"
        ;;
    *)
        echo "extract-vcl: unknown snippet type '$type' in $f" >&2
        exit 5
        ;;
    esac
    n=$((n + 1))
done

if [ "$n" -eq 0 ]; then
    echo "extract-vcl: no snippets found in $TF_FILE" >&2
    exit 6
fi

echo "extract-vcl: wrote $n snippet(s) to $LINT_DIR" >&2
echo "$LINT_DIR"
